import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("公共加载覆盖会话、并发内容读取和失败重试，保留编辑输入", async ({ page }) => {
  const credential = JSON.parse(await readFile("../backend/storage/private/browser-verification.json", "utf8"));
  let releaseSession!: () => void;
  const sessionGate = new Promise<void>((resolve) => { releaseSession = resolve; });
  await page.route("**/api/v1/admin/auth/session", async (route) => { await sessionGate; await route.continue(); });
  await page.goto("/admin/global/settings");
  await expect(page.locator(".loading-card")).toBeVisible();
  await expect(page.locator(".loading-card .admin-loading-indicator")).toBeVisible();
  releaseSession();
  await page.getByLabel("用户名", { exact: true }).fill(credential.username);
  await page.getByLabel("密码", { exact: true }).fill(credential.password ?? credential.temporaryPassword);
  let releaseSettings!: () => void;
  const settingsGate = new Promise<void>((resolve) => { releaseSettings = resolve; });
  await page.route("**/api/v1/admin/resources/settings/*", async (route) => { await settingsGate; await route.continue(); });
  await page.getByRole("button", { name: "登录后台", exact: true }).click();
  await expect(page.getByText("正在读取公共内容", { exact: true })).toBeVisible();
  await expect(page.locator(".admin-header .admin-loading-compact")).toBeVisible();
  releaseSettings();
  await expect(page.getByLabel("网站名称", { exact: true })).toBeVisible();
  await expect(page.locator(".admin-header .admin-loading-compact")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "刷新数据", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "历史与恢复", exact: true })).toHaveCount(0);
  const original = await page.getByLabel("网站名称", { exact: true }).inputValue();
  await page.getByLabel("网站名称", { exact: true }).fill("未发布的加载验收输入");
  let releaseSave!: () => void;
  const saveGate = new Promise<void>((resolve) => { releaseSave = resolve; });
  await page.route("**/api/v1/admin/resources/settings/company_name", async (route) => {
    if (route.request().method() !== "PATCH") return route.continue();
    await saveGate;
    await route.fulfill({ status: 503, json: { Code: 5000, Messages: "加载验收受控失败", Data: null } });
  });
  const save = page.locator('[data-global-group="name"]').getByRole("button", { name: "保存并发布", exact: true });
  await save.click();
  await expect(save.locator(".admin-loading-indicator")).toBeVisible();
  await expect(save).toBeDisabled();
  releaseSave();
  await expect(page.getByText("加载验收受控失败", { exact: true })).toBeVisible();
  await expect(page.getByLabel("网站名称", { exact: true })).toHaveValue("未发布的加载验收输入");
  await expect(page.locator(".admin-header .admin-loading-compact")).toHaveCount(0);
  await page.getByLabel("网站名称", { exact: true }).fill(original);
  await page.unroute("**/api/v1/admin/resources/settings/*");
  await page.reload();
  await expect(page.getByLabel("网站名称", { exact: true })).toHaveValue(original);
  await page.locator(".sidebar nav").getByRole("button", { name: "概览", exact: true }).click();
  await expect(page.getByRole("button", { name: "刷新数据", exact: true })).toBeVisible();
});
